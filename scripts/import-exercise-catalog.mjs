import { mkdir, writeFile } from 'node:fs/promises';

// Deliberate updates only: runtime searches never depend on GitHub availability.
const revision = process.argv[2] ?? 'f00c92c7dcf1216a928a52c3706c7ce8e2f71ed5';
if (!/^[a-f0-9]{40}$/.test(revision)) throw new Error('Pass a full upstream commit SHA.');
const base = `https://raw.githubusercontent.com/yuhonas/free-exercise-db/${revision}`;
const response = await fetch(`${base}/dist/exercises.json`);
if (!response.ok) throw new Error(`Catalogue download failed: ${response.status}`);
const data = await response.json();
const definitions = data.map(({ id, name, equipment, primaryMuscles, secondaryMuscles, instructions, category, images }) => ({
  id, name, equipment: equipment ?? 'other', primaryMuscles, secondaryMuscles, instructions, category, images,
}));
const slugs = definitions.map(({ id }) => `db-${id.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`);
if (new Set(slugs).size !== slugs.length || definitions.some((item) => !item.id || !item.name || item.images.some((path) => !/^[a-zA-Z0-9_()\-./]+\.jpg$/.test(path) || path.includes('..')))) throw new Error('Invalid or duplicate exercise identity/image path.');
await mkdir(new URL('../src/data/', import.meta.url), { recursive: true });
await writeFile(new URL('../src/data/exercises.ts', import.meta.url), `// Generated by scripts/import-exercise-catalog.mjs. Free Exercise DB (Unlicense).\nexport const EXERCISE_DB_REVISION = ${JSON.stringify(revision)};\nexport type ExerciseDefinition = { id: string; name: string; equipment: string; primaryMuscles: string[]; secondaryMuscles: string[]; instructions: string[]; category: string; images: string[] };\nexport const exerciseDefinitions: ExerciseDefinition[] = ${JSON.stringify(definitions)};\n`);
const license = await fetch(`${base}/LICENSE.md`);
if (!license.ok) throw new Error('License download failed.');
await writeFile(new URL('../src/data/FREE-EXERCISE-DB-LICENSE.md', import.meta.url), await license.text());
console.log(`Imported ${definitions.length} definitions from ${revision}.`);

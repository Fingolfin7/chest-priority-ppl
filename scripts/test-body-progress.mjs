 const png=await page.evaluate(()=>{const canvas=document.createElement('canvas');canvas.width=200;canvas.height=300;const ctx=canvas.getContext('2d');ctx.fillStyle='#63a3bd';ctx.fillRect(0,0,200,300);return canvas.toDataURL('image/png').split(',')[1];});
